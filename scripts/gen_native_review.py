#!/usr/bin/env python
"""Generate the native-speaker review sheet for user-facing Bangla copy (AUD-G-06 / G-27).

The audit cannot certify Bangla language quality (master prompt T14); it can
only collect every string a user can see, with its location, so a native
speaker can review it. This script is the collector.

Sources, in order:

* ``apps/web/src/i18n.ts`` - the Bangla dictionary; keys and values.
* other ``apps/web/src`` TypeScript/TSX files - Bangla string literals that are
  not routed through the dictionary.
* ``apps/api/src/bangla_gpt_api`` - Bangla string literals the API can put in
  front of a user (refusals, safety copy, digests, prompts). Word-list and
  lexicon literals are skipped: a row is only collected when the literal reads
  like a sentence (contains a space and at least six Bengali characters).

Usage::

    python scripts/gen_native_review.py             # write the sheet
    python scripts/gen_native_review.py --check     # fail if it is stale (CI)

The sheet is generated, never hand-edited: review decisions belong in
``docs/native-review-sheet.md`` and in the glossary, not in the table.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
WEB = REPO / "apps" / "web" / "src"
API = REPO / "apps" / "api" / "src" / "bangla_gpt_api"
OUT = REPO / "docs" / "native-review" / "ui-strings.md"

BANGLA = re.compile("[\u0980-\u09FF]")
DICT_ENTRY = re.compile(
    r'^\s{2}([A-Za-z_][A-Za-z0-9_]*):\s*"((?:[^"\\]|\\.)*)",?\s*$', re.MULTILINE
)
TS_STRING = re.compile(r'"[^"\n]*[\u0980-\u09FF][^"\n]*"')
PY_STRING = re.compile(
    "[\"'][^\"'\\n]*[\u0980-\u09FF][^\"'\\n]*[\"']"
)

HEADER = """# Native-speaker review sheet - user-facing Bangla strings

NEEDS NATIVE REVIEW. Nothing in this file has been checked for linguistic
quality, naturalness, register or curricular correctness by a native speaker or
a teacher. It is a collection aid, generated by `scripts/gen_native_review.py`.

How to use it:

1. Read a row: `file:line`, the string as it appears, and a concern column that
   the reviewer fills in. Leave the concern empty when the string is fine.
2. Mark decisions in `docs/native-review-sheet.md` (the review record) and, for
   repeated terms, in `docs/i18n-glossary.md` (the term list that
   `scripts/check_glossary.py` enforces).
3. Rows marked `(literal)` are strings written directly in a source file rather
   than in the dictionary - the same review applies.

Concerns worth flagging: unnatural or machine-translated phrasing; mixed formal
and colloquial register; a term that contradicts the glossary; digits used in
the wrong script; text that would not be understood by a class 6 student; a
translation that changes the meaning of the English original.

| # | file:line | key / symbol | text | concern |
|---|-----------|--------------|------|---------|
"""


def _unescape(value: str) -> str:
    return value.replace("\\n", " ").replace('\\"', '"').replace("\\\\", "\\").strip()


def dict_rows() -> list[tuple[str, str, str]]:
    """(location, key, text) for every entry of the Bangla dictionary.

    Values wrapped over several lines by the formatter are joined first: the
    sheet shows the string a user actually reads, exactly once.
    """
    path = WEB / "i18n.ts"
    text = path.read_text(encoding="utf-8")
    start = text.index("const bn = {")
    end = text.index("const en: Dict = {", start)
    block = text[start:end]
    base_line = text[:start].count("\n") + 1
    rows: list[tuple[str, str, str]] = []
    for match in DICT_ENTRY.finditer(block):
        key, value = match.groups()
        lineno = base_line + block[: match.start()].count("\n")
        rows.append(
            (f"{path.relative_to(REPO).as_posix()}:{lineno}", key, _unescape(value))
        )
    return rows


def _is_copy(text: str) -> bool:
    """Prose filter for the literal scans: sentences, not word lists."""
    if len(BANGLA.findall(text)) < 6:
        return False
    return " " in text


def _literal_rows(path: Path, pattern: re.Pattern[str]) -> list[tuple[str, str, str]]:
    rows: list[tuple[str, str, str]] = []
    for lineno, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if line.lstrip().startswith("#"):
            continue
        for match in pattern.finditer(line):
            text = match.group(0)[1:-1].strip()
            if _is_copy(text):
                rows.append(
                    (f"{path.relative_to(REPO).as_posix()}:{lineno}", "(literal)", text)
                )
    return rows


def code_rows() -> list[tuple[str, str, str]]:
    rows: list[tuple[str, str, str]] = []
    for path in sorted(WEB.rglob("*.ts*")):
        if "test" in path.parts or path.name == "i18n.ts":
            continue
        rows.extend(_literal_rows(path, TS_STRING))
    for path in sorted(API.rglob("*.py")):
        rows.extend(_literal_rows(path, PY_STRING))
    return rows


def build() -> str:
    rows = dict_rows()
    extra = code_rows()
    body = [HEADER]
    for i, (loc, key, text) in enumerate(rows + extra, start=1):
        safe = text.replace("|", "\\|").replace("\n", " ")
        body.append(f"| {i} | {loc} | {key} | {safe} | |")
    body.append("")
    body.append(
        f"Total rows: {len(rows) + len(extra)} "
        f"({len(rows)} dictionary, {len(extra)} literals)."
    )
    body.append("")
    return "\n".join(body)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero when the committed sheet is not the generated one",
    )
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args()

    generated = build()
    out = args.out if args.out.is_absolute() else REPO / args.out
    if args.check:
        if not out.exists():
            print("::error::the review sheet is missing; run scripts/gen_native_review.py")
            return 1
        if out.read_text(encoding="utf-8") != generated:
            print(
                "::error::the review sheet is stale; run scripts/gen_native_review.py",
                file=sys.stderr,
            )
            return 1
        print(f"{out.relative_to(REPO).as_posix()} is up to date")
        return 0

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(generated, encoding="utf-8", newline="\n")
    print(f"wrote {out.relative_to(REPO).as_posix()} ({generated.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
