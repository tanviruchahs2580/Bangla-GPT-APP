const DICTS: Record<Lang, Dict> = { bn, en }

let current: Lang = (localStorage.getItem('bgpt_lang') as Lang) || 'bn'
const listeners = new Set<() => void>()

export function getLang(): Lang {
  return current
}

export function setLang(lang: Lang): void {
  current = lang
  localStorage.setItem('bgpt_lang', lang)
  listeners.forEach((fn) => fn())
}

export function onLangChange(fn: () => void): () => void {
  listeners.add(fn)
  return () => listeners.delete(fn)
}

/** Translate a key; `{var}` placeholders are replaced positionally by named props. */
export function t(key: keyof Dict, vars?: Record<string, string | number>): string {
  let out: string = DICTS[current][key]
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      out = out.replaceAll(`{${k}}`, String(v))
    }
  }
  return out
}
