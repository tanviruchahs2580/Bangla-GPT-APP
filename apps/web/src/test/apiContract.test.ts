/**
 * FE-05: the client/OpenAPI contract module's own contract.
 *
 * The live comparison runs in the e2e suite (it needs the served
 * `/openapi.json`); these cases pin the extractor so a regex that silently
 * stops matching cannot make the live check vacuous. The fixture strings
 * mirror the shapes that actually occur in `src/api.ts` and the pages.
 */
import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import {
  extractClientCalls,
  flattenDeclaration,
  missingFromSchema,
  openApiOperations,
  parseTypeDeclarations,
  resolveJsonResponse,
  resolveTypeArg,
  typeMismatches,
  type OpenApiSchema,
  type TsProperty,
} from "../lib/apiContract";

function clientSourceText(): string {
  const files: string[] = [];
  const walk = (dir: string): void => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) {
        if (!["node_modules", "test"].includes(entry.name)) walk(path);
      } else if (/\.(ts|tsx)$/.test(entry.name)) {
        files.push(path);
      }
    }
  };
  walk(join(process.cwd(), "src"));
  return files.map((file) => readFileSync(file, "utf8")).join("\n");
}

describe("normalizePath", () => {
  it("turns path parameters into {param} and drops query strings", () => {
    const calls = extractClientCalls(`
      get<A>(\`/learn/subjects/\${encodeURIComponent(subject)}/chapters\`);
      get<B>(\`/learn/progress?\${qs}\`);
      get<C>(\`/learn/subjects\${classLevel ? \`?class_level=\${classLevel}\` : ""}\`);
      get<D>("/users/me");
    `);
    expect(calls.map((c) => `${c.method} ${c.path}`)).toEqual([
      "get /learn/progress",
      "get /learn/subjects",
      "get /learn/subjects/{param}/chapters",
      "get /users/me",
    ]);
  });

  it("maps the helper verbs the client uses", () => {
    const calls = extractClientCalls(`
      post<A>("/quizzes/1/submit", {});
      patch<B>("/notes/2", {});
      del("/notes/2");
      postStream<C>("/tutor/conversations/1/messages/stream", {}, () => {}, {});
    `);
    expect(calls.map((c) => `${c.method} ${c.path}`)).toEqual([
      "delete /notes/2",
      "patch /notes/2",
      "post /quizzes/1/submit",
      "post /tutor/conversations/1/messages/stream",
    ]);
  });

  it("ignores non-route and non-literal calls", () => {
    const calls = extractClientCalls(`
      localStorage.getItem("bgpt_token");
      const qs = new URLSearchParams();
      get<A>(somePath);
      post(helper());
    `);
    expect(calls).toEqual([]);
  });
});

describe("missingFromSchema", () => {
  const schema = {
    paths: {
      "/learn/subjects/{subject}/chapters": { get: {} },
      "/notes/{note_id}": { delete: {}, patch: {} },
    },
  };

  it("accepts calls whose path and method the schema declares", () => {
    const calls = extractClientCalls(`
      get<A>(\`/learn/subjects/\${s}/chapters\`);
      del(\`/notes/\${id}\`);
    `);
    expect(missingFromSchema(calls, schema)).toEqual([]);
  });

  it("flags a renamed segment and a wrong method", () => {
    const calls = extractClientCalls(`
      get<A>(\`/learn/subjects/\${s}/chapters\`);
      get<B>(\`/learn/topics/\${s}/chapters\`);
      post<C>(\`/notes/\${id}\`, {});
    `);
    expect(missingFromSchema(calls, schema)).toEqual([
      "get /learn/topics/{param}/chapters",
      "post /notes/{param}",
    ]);
  });

  it("canonicalizes placeholder names on both sides only", () => {
    const operations = openApiOperations(schema);
    expect(operations.has("get /learn/subjects/{param}/chapters")).toBe(true);
    expect(operations.has("get /learn/topics/{param}/chapters")).toBe(false);
  });
});

/**
 * F-157 residual: the extractor's own cases above run on fixtures, and the
 * live schema comparison needs servers (e2e). These cases run the extractor
 * over the shipped client sources, so regex rot or a client call that stops
 * being a plain literal fails here too -- next to the code that parses it.
 */
describe("the extractor against the shipped client", () => {
  const calls = extractClientCalls(clientSourceText());
  const keys = new Set(calls.map((c) => `${c.method} ${c.path}`));

  it("still finds the >60 calls the e2e floor claims", () => {
    expect(calls.length).toBeGreaterThan(60);
  });

  it("finds the release-critical calls", () => {
    for (const expected of [
      "post /auth/register",
      "post /auth/login",
      "get /users/me",
      "post /tutor/conversations/{param}/messages/stream",
      "post /quizzes/{param}/submit",
    ]) {
      expect(keys.has(expected), `missing ${expected}`).toBe(true);
    }
  });
});

/**
 * F-157: the OpenAPI-to-client contract, against a committed snapshot of
 * `app.openapi()` (regenerated by apps/api/scripts/export_openapi_types.py;
 * the api CI job re-runs the exporter and diffs, so a schema change that
 * ships without the fixture following fails there). Three checks:
 *
 *  1. every client call is declared by the schema (the offline form of the
 *     e2e route comparison);
 *  2. every schema operation is called by the client or documented in
 *     SCHEMA_ONLY_OPERATIONS, so no route can silently disappear;
 *  3. every typed response mirrors the schema component the operation
 *     returns -- the hand-maintained `types.ts` cannot drift field-by-field.
 *
 * Deliberate narrow reads (a call site that reads two fields of a wide
 * component) stay honest through the per-call/field exemption maps: each
 * carries its reason, and the tests fail on a stale entry so the maps can
 * only track reality.
 */
describe("the committed OpenAPI fixture against the client", () => {
  const fixturePath = join(process.cwd(), "src/test/fixtures/openapi.json");
  const doc: OpenApiSchema = JSON.parse(readFileSync(fixturePath, "utf8"));
  const sourceText = clientSourceText();
  const calls = extractClientCalls(sourceText);
  const declarations = parseTypeDeclarations(sourceText);
  const callKeys = new Set(calls.map((c) => `${c.method} ${c.path}`));
  const operations = openApiOperations(doc);

  /** Infrastructure probes: consumed by the orchestrator, never the client. */
  const INFRA_PROBE =
    "infrastructure probe (compose/Kubernetes), not a client route";
  /** Authed binary downloads: fetched through getBlob, no JSON body. */
  const BLOB_DOWNLOAD =
    "authed blob download through getBlob(); no JSON response contract";
  /** Admin/ops surface with no web screen on the routes App.tsx mounts. */
  const OPS_ONLY = "operations/admin surface; no web screen consumes it today";
  /** The surface exists for API clients; the web UI does not call it yet. */
  const NOT_WIRED =
    "no web UI consumer today; wiring one up must bring its client type";

  /** Schema operations no client helper calls, each with the reason. */
  const SCHEMA_ONLY_OPERATIONS: Record<string, string> = {
    "delete /admin/users/{param}/impersonate":
      "impersonation exits through POST /auth/impersonate/exit",
    "get /admin/audit": OPS_ONLY,
    "get /admin/reports/aggregate": OPS_ONLY,
    "get /admin/schools":
      "the admin card reads /admin/schools/stats (per-school rows)",
    "get /admin/system/info": OPS_ONLY,
    "get /health": INFRA_PROBE,
    "get /kg/gaps": OPS_ONLY,
    "get /live": INFRA_PROBE,
    "get /ready": INFRA_PROBE,
    "get /schools/mine": NOT_WIRED,
    "get /students/{param}":
      "roster rows arrive via /teacher/classrooms/{param}/roster",
    "get /students/{param}/consent": NOT_WIRED,
    "get /teacher/content": OPS_ONLY,
    "get /teacher/content/history": OPS_ONLY,
    "get /teacher/documents/{param}":
      "the list (GET /teacher/documents) already carries the rows",
    "get /teacher/documents/{param}/pdf": BLOB_DOWNLOAD,
    "get /teacher/jobs/{param}":
      "the create hub polls the list (GET /teacher/jobs)",
    "get /teacher/qpapers/{param}":
      "the list (GET /teacher/qpapers) already carries the rows",
    "get /teacher/qpapers/{param}/pdf": BLOB_DOWNLOAD,
    "get /teacher/students":
      "roster rows arrive via /teacher/classrooms/{param}/roster",
    "post /auth/join-school": NOT_WIRED,
    "post /auth/mfa/disable": NOT_WIRED,
    "post /auth/mfa/enroll": NOT_WIRED,
    "post /auth/mfa/verify": NOT_WIRED,
    "post /auth/renew":
      "the 401 renewal interceptor fetches it raw (api.ts); the body is TokenResponse",
    "post /kg/rebuild": OPS_ONLY,
    "post /parents/link":
      "the UI redeems the student's code via /parents/link/invite",
    "post /schools/{param}/classes":
      "classrooms are created via POST /teacher/classrooms",
    "post /students/{param}/consent/reconfirm": NOT_WIRED,
    "post /teacher/content/generate": OPS_ONLY,
    "post /tutor/conversations/{param}/messages":
      "the tutor UI streams (/messages/stream)",
    "put /teacher/content": OPS_ONLY,
  };

  /** Untyped calls whose operation returns a named component, with the reason
   * the client reads no component field. */
  const UNTYPED_CALLS: Record<string, string> = {
    "delete /students/me/memory":
      "the del wrapper ignores the body; the page clears its local memory state",
    "patch /admin/users/{param}/role":
      "the dashboard refetches the user list afterwards; the body is not read",
    "post /admin/schools":
      "the card refetches /admin/schools/stats afterwards; the created row is not read",
    "post /auth/register":
      "201 RegisterResponse or 202 (verification pending); the wrapper resolves void and the session comes from the follow-up /users/me probe",
    "post /feedback": "the body ({status}) is not read by the tutor surface",
    "post /revision/{param}/review":
      "the review list is refetched; the updated item body is not read",
  };

  /** Field-level requiredness the contract allows on one call (`call#field`). */
  const FIELD_EXEMPTIONS: Record<string, string> = {
    "get /tutor/conversations/{param}/messages#created_at":
      "ChatMessage also models client-built optimistic placeholders, and the SSE done event carries no created_at, so the UI type keeps it optional",
  };

  /** Whole-call shape exemptions (an index signature against a component). */
  const SHAPE_EXEMPTIONS: Record<string, string> = {
    "get /users/me/export":
      "the export document is written to a Blob verbatim and no field is read, so an index signature is the honest client type",
  };

  it("has a fixture that actually carries the route set", () => {
    expect(Object.keys(doc.paths ?? {}).length).toBeGreaterThan(100);
  });

  it("declares every client call (the offline form of the e2e check)", () => {
    expect(missingFromSchema(calls, doc)).toEqual([]);
  });

  it("calls every schema operation or documents the gap", () => {
    const undocumented = [...operations].filter(
      (op) => !callKeys.has(op) && !SCHEMA_ONLY_OPERATIONS[op],
    );
    expect(
      undocumented,
      "new schema operations need a client call or an entry above",
    ).toEqual([]);
    const stale = Object.keys(SCHEMA_ONLY_OPERATIONS).filter(
      (op) => callKeys.has(op) || !operations.has(op),
    );
    expect(
      stale,
      "exclusions must track reality: drop the stale entries",
    ).toEqual([]);
  });

  it("documents every untyped call that returns a named component", () => {
    const untyped = calls
      .filter((c) => !c.typeArgs)
      .map((c) => `${c.method} ${c.path}`)
      .filter(
        (key) =>
          resolveJsonResponse(doc, ...(key.split(" ") as [string, string]))
            .kind === "ref",
      );
    const missing = untyped.filter((key) => !UNTYPED_CALLS[key]);
    expect(
      missing,
      "type the call or document why the body goes unread",
    ).toEqual([]);
    const stale = Object.keys(UNTYPED_CALLS).filter(
      (key) => !untyped.includes(key),
    );
    expect(
      stale,
      "exclusions must track reality: drop the stale entries",
    ).toEqual([]);
  });

  it("declares no type twice with different fields", () => {
    const ambiguous = [...declarations.entries()]
      .filter(([, list]) => list.length > 1)
      .filter(([, list]) => {
        const signatures = new Set(
          list.map((d) =>
            d.properties
              .map((p) => `${p.name}${p.optional ? "?" : ""}`)
              .join(","),
          ),
        );
        return signatures.size > 1;
      })
      .map(([name]) => name);
    expect(ambiguous, "consolidate the duplicate declarations").toEqual([]);
  });

  it("mirrors every typed response's schema component", () => {
    const problems: string[] = [];
    const usedFieldExemptions = new Set<string>();
    for (const call of calls) {
      for (const typeArg of call.typeArgs ?? []) {
        const key = `${call.method} ${call.path}`;
        const response = resolveJsonResponse(doc, call.method, call.path);
        if (response.kind !== "ref") continue;
        const resolved = resolveTypeArg(typeArg);
        if (!resolved) {
          problems.push(`${key}: unresolvable type argument <${typeArg}>`);
          continue;
        }
        if (resolved.indexSignature) {
          if (
            Object.keys(response.properties).length > 0 &&
            !SHAPE_EXEMPTIONS[key]
          ) {
            problems.push(
              `${key}: <Record<...>> against named component ${response.component}`,
            );
          }
          continue;
        }
        if (resolved.array !== response.array) {
          problems.push(
            `${key}: array-ness mismatch, <${typeArg}> vs component ${response.component}`,
          );
          continue;
        }
        let properties: TsProperty[];
        if (resolved.inline) {
          properties = resolved.inline;
        } else {
          const declaration = resolved.name
            ? declarations.get(resolved.name)?.[0]
            : undefined;
          if (!declaration) {
            problems.push(
              `${key}: type <${resolved.name ?? typeArg}> has no parseable declaration`,
            );
            continue;
          }
          properties = flattenDeclaration(declaration, declarations);
        }
        for (const problem of typeMismatches(response, properties, {
          call: key,
          tsType: resolved.name ?? typeArg,
          component: response.component,
        })) {
          const field = /`([^`]+)`/.exec(problem)?.[1];
          const exemptionKey = field === undefined ? "" : `${key}#${field}`;
          if (
            exemptionKey !== "" &&
            FIELD_EXEMPTIONS[exemptionKey] !== undefined
          ) {
            usedFieldExemptions.add(exemptionKey);
            continue;
          }
          problems.push(problem);
        }
      }
    }
    expect(problems, "align the client type with the schema").toEqual([]);
    const staleExemptions = Object.keys(FIELD_EXEMPTIONS).filter(
      (key) => !usedFieldExemptions.has(key),
    );
    expect(
      staleExemptions,
      "exclusions must track reality: drop the stale entries",
    ).toEqual([]);
  });
});
