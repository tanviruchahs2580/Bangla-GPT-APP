"""Offline breached-password check (AUD-B-06, NIST SP 800-63B §5.1.1.2).

The audit's B register requirement was "no breached-password corpus check":
``auth/security.py`` refused the most obvious guesses (``COMMON_PASSWORDS``)
but a breached value one edit further out -- ``qwertyuiop``, ``1q2w3e4r``,
``Iloveyou2!``, ``asdf1234`` -- was accepted (reproduced against the pre-fix
HEAD in ``.audit/evidence/E-R2-b2-001``). NIST SP 800-63B (Rev. 4,
800-63B-4, §3.1.1.2) requires a check against a list of commonly-used and
breached passwords, including the same value with different capitalizations.

Design constraints (this repo, not a generic library):

* **Offline, no network.** The list is a small embedded frozenset. Nothing is
  fetched, no file is read at import time, no API is called; a registration
  cannot block on the internet or leak the candidate password to a
  third-party breach service (which would itself be a privacy problem on a
  children's platform).
* **Small on purpose.** This is the floor that closes the audit finding, not a
  replacement for a full corpus (Have I Been Pwned's 800M entries are not
  shippable inside a source tree). The list carries the top of the public
  RockYou-style frequency lists plus the country/context words that this
  product's users actually favour ("bangladesh", "dhaka", "student").
* **Shared normalisation.** ``fold_variants`` is the single transformation
  used for both this list and ``auth.security.COMMON_PASSWORDS``, so the two
  checks cannot drift apart in how they read a candidate.
"""

from __future__ import annotations

#: Same shape mappings the small blocklist uses ("P@ssw0rd1" is "password1").
_LEET = str.maketrans(
    {"@": "a", "0": "o", "1": "l", "3": "e", "4": "a", "5": "s", "7": "t", "$": "s"}
)

#: What people append or wrap a base word with. Stripping these is how
#: "Password123!" matches the base entry "password".
_TRAILING_DIGITS = "0123456789"
_TRAILING_SYMBOLS = "!@#$%^&*()_+-=.,?~:;'\"<>[]{}|\\/"


def _mangle_forms(base: str) -> set[str]:
    """The edits a guesser's rule engine applies to one base form.

    Trailing digits/symbols are stripped because appending them is the most
    common way a person mangles a base word ("password" -> "password123",
    "iloveyou" -> "iloveyou2!"). Separators are removed wholesale because
    "mon-key_123" is the same guess as "monkey123".
    """
    out: set[str] = set()
    separators = str.maketrans("", "", " -_.")
    for form in (base, base.translate(separators)):
        if not form:
            continue
        out.add(form)
        digits_stripped = form.rstrip(_TRAILING_DIGITS)
        punct_stripped = form.rstrip(_TRAILING_SYMBOLS)
        out.update(
            variant
            for variant in (
                digits_stripped,
                punct_stripped,
                punct_stripped.rstrip(_TRAILING_DIGITS),
            )
            if variant
        )
    return out


def fold_variants(password: str) -> set[str]:
    """The shapes a guesser would actually try for this candidate.

    Both the plain lowercase form and the leet-folded form are kept. Either
    transformation on its own makes the blocklist silently useless: folding
    turns "12345678" into "l2eas6t8", which matches nothing in any word list,
    and collapsing repeated characters turns "password" into "pasword", which
    also matches nothing.
    """
    lowered = (password or "").strip().lower()
    if not lowered:
        return set()
    out: set[str] = set()
    for form in (lowered, lowered.translate(_LEET)):
        out |= _mangle_forms(form)
    return out


