def is_breached_password(password: str) -> bool:
    """True when the candidate matches the embedded breached-password list.

    Used on registration, reset and change-password: a list checked only at
    registration is bypassed the moment a user resets to a leaked value.
    """
    if not (password or "").strip():
        return False
    return bool(fold_variants(password) & BREACHED_PASSWORDS)


