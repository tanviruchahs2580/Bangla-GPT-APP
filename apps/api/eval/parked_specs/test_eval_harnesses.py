"""Regression tests for the two committed evaluation harnesses.

Both scripts are what make the retrieval numbers in `data/nctb/retrieval_eval.json`
and the claims in docs/RAG_ARCHITECTURE.md reproducible. Each one had a defect
that made its published output unreachable or meaningless:

* `evaluate_nctb_retrieval.py` called `TutorService._grounded`, a method that no
  longer exists, so the script died with AttributeError on its adversarial pass.
  The committed metrics could not be regenerated by their own tooling.
* `evaluate_golden.py` counted every refusal item as a hit@3 hit, handing out
  seven free points out of twenty-four, and never gated the metric it printed.

These tests import the modules and assert the contract, so a rename on the
service side fails here instead of silently invalidating a published number.
"""

import importlib.util
import sys
from pathlib import Path

import pytest

API_ROOT = Path(__file__).resolve().parents[1]
SCRIPTS = API_ROOT / "scripts"


def _load(name: str):
    spec = importlib.util.spec_from_file_location(name, SCRIPTS / f"{name}.py")
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


@pytest.fixture(scope="module")
def nctb_eval():
    return _load("evaluate_nctb_retrieval")


@pytest.fixture(scope="module")
def golden_eval():
    return _load("evaluate_golden")


# ---------------------------------------------------------------------------
# evaluate_nctb_retrieval.py
# ---------------------------------------------------------------------------


def test_nctb_harness_calls_only_methods_that_exist(nctb_eval) -> None:
    """The harness must not reference a renamed or removed service method.

    ``_grounded`` was renamed to ``_gate`` and now takes the hit list rather than
    a score and a text. Anything the harness reaches for through a
    ``TutorService`` instance has to exist on the real class, otherwise the
    committed metrics in data/nctb/retrieval_eval.json cannot be regenerated by
    the script that is supposed to produce them.
    """
    import re

    from bangla_gpt_api.data.loader import load_sample_corpus
    from bangla_gpt_api.providers.mock import MockLLMProvider
    from bangla_gpt_api.retrieval.bm25 import BM25Index
    from bangla_gpt_api.services.tutor import TutorService

    # Resolve against a real instance: some of what the harness reads (top_k)
    # is set in __init__ rather than on the class.
    tutor = TutorService(index=BM25Index(load_sample_corpus()), provider=MockLLMProvider())

    source = (SCRIPTS / "evaluate_nctb_retrieval.py").read_text(encoding="utf-8")
    referenced = set(re.findall(r"\btutor\.([A-Za-z_][A-Za-z0-9_]*)", source))

    missing = sorted(name for name in referenced if not hasattr(tutor, name))
    assert not missing, (
        f"evaluate_nctb_retrieval.py uses TutorService.{missing}, which does not "
        "exist; the committed retrieval metrics cannot be regenerated"
    )
    # The gate the harness depends on must be the one that takes a hit list.
    assert "_gate" in referenced


def test_nctb_harness_gate_passes_the_full_hit_list(nctb_eval) -> None:
    """``_gate`` scores against every candidate chunk, not a single top hit.

    Passing ``top_k=1`` would make the adversarial refusal rate look better than
    the service's real behaviour, because the gate accepts any one chunk that
    covers the question.
    """
    source = (SCRIPTS / "evaluate_nctb_retrieval.py").read_text(encoding="utf-8")
    assert "tutor._gate(" in source
    assert "top_k=1)" not in source.split("tutor._gate(")[0].rsplit("\n", 1)[-1]


def test_nctb_harness_reports_the_expected_metric_keys(nctb_eval) -> None:
    """The report shape docs/RAG_ARCHITECTURE.md quotes must stay stable."""
    source = (SCRIPTS / "evaluate_nctb_retrieval.py").read_text(encoding="utf-8")
    for key in (
        "family_A_self_sentence",
        "family_B_chapter_title",
        "family_C_adversarial_refusal_rate",
    ):
        assert key in source, f"report key {key} disappeared from the harness"


