def test_golden_report_separates_retrieval_from_refusal(golden_eval, tmp_path, monkeypatch):
    """A refusal must not count as a retrieval hit.

    The old harness added ``chapter_hit or expected_grounded is False`` to the
    hit@3 numerator, so every out-of-scope item was a free point and the metric
    could not distinguish "found the right chapter" from "declined to answer".
    """
    from bangla_gpt_api.curriculum.models import Chunk, CurriculumMeta

    meta = CurriculumMeta(
        curriculum_year=2023,
        class_level=6,
        subject="science",
        book="Science",
        source="sample",
        chapter="কোষ",
        page=1,
    )
    chunks = [
        Chunk(id=f"c{i}", meta=meta, text="কোষ হলো জীবদেভর গঠনগত ও ক্রিয়াগত একক।") for i in range(4)
    ]
    dataset = tmp_path / "golden.json"
    dataset.write_text(
        """
        [
          {"question": "কোষ কী?", "class_level": 6, "subject": "science",
           "expected_grounded": true, "expected_chapter_contains": "কোষ"},
          {"question": "ক্রিকেট বিশ্বকাপ কে জিতেছিল?", "class_level": 6,
           "subject": "science", "expected_grounded": false}
        ]
        """,
        encoding="utf-8",
    )
    out = tmp_path / "report.json"
    monkeypatch.setattr(golden_eval, "GOLDEN_PATH", dataset)
    monkeypatch.setattr(golden_eval, "REPORT_PATH", out)
    monkeypatch.setattr(golden_eval, "load_sample_corpus", lambda: chunks, raising=False)

    exit_code = golden_eval.main()

    report = golden_eval.json.loads(out.read_text(encoding="utf-8"))
    assert report["positives"] == 1
    assert report["negatives"] == 1
    # One hit over one answerable item -- the refusal contributed nothing.
    assert report["hit_at_3"] == 1.0
    assert report["refusal_accuracy"] == 1.0
    assert report["grounded_accuracy"] == 1.0
    assert exit_code == 0


def test_golden_harness_gates_hit_at_3(golden_eval, tmp_path, monkeypatch) -> None:
    """A retrieval regression must fail the run, not just be printed.

    ``hit_at_3`` used to be computed, written to a report and never checked;
    the workflow name promised a hit@3 gate that did not exist.
    """
    from bangla_gpt_api.curriculum.models import Chunk, CurriculumMeta

    meta = CurriculumMeta(
        curriculum_year=2023,
        class_level=6,
        subject="science",
        book="Science",
        source="sample",
        chapter="অন্য অধ্যায়",
        page=1,
    )
    chunks = [
        Chunk(id=f"c{i}", meta=meta, text="কোষ হলো জীবদেভর গঠনগত ও ক্রিয়াগত একক।") for i in range(4)
    ]
    dataset = tmp_path / "golden.json"
    # Every item is answerable and expects a chapter that is not in the corpus.
    dataset.write_text(
        """
        [{"question": "কোষ কী?", "class_level": 6, "subject": "science",
          "expected_grounded": true, "expected_chapter_contains": "অনুপস্থিত"}]
        """,
        encoding="utf-8",
    )
    out = tmp_path / "report.json"
    monkeypatch.setattr(golden_eval, "GOLDEN_PATH", dataset)
    monkeypatch.setattr(golden_eval, "REPORT_PATH", out)
    monkeypatch.setattr(golden_eval, "load_sample_corpus", lambda: chunks, raising=False)

    exit_code = golden_eval.main()

    report = golden_eval.json.loads(out.read_text(encoding="utf-8"))
    assert report["hit_at_3"] == 0.0
    assert exit_code == 1, "a total retrieval miss must fail the gate"


